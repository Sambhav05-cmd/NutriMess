import test from 'node:test';
import assert from 'node:assert/strict';
import { once } from 'node:events';
import fs from 'node:fs/promises';
import { JSDOM, VirtualConsole } from 'jsdom';
process.env.DB_PATH=':memory:';
const { app } = await import('../server/index.js');

test('frontend renders and completes profile, menu, food-log and planner flows',async()=>{
  const server=app.listen(0,'127.0.0.1');await once(server,'listening');
  const base=`http://127.0.0.1:${server.address().port}`;
  const response=await fetch(base);
  assert.equal(response.status,200);
  assert.ok(response.headers.get('content-security-policy').includes("script-src 'self'"));
  assert.ok(!response.headers.get('content-security-policy').includes('upgrade-insecure-requests'),'LAN HTTP scripts must not be upgraded to HTTPS');
  assert.equal(response.headers.get('strict-transport-security'),null);
  const errors=[],virtualConsole=new VirtualConsole();
  virtualConsole.on('jsdomError',e=>errors.push(e));
  const dom=new JSDOM(await response.text(),{url:base,runScripts:'outside-only',virtualConsole});
  const {window:w}=dom;let cookie='';
  w.fetch=async(url,options={})=>{
    const res=await fetch(new URL(url,base),{...options,headers:{...options.headers,cookie}});
    if(res.headers.get('set-cookie'))cookie=res.headers.get('set-cookie').split(';')[0];
    return res;
  };
  w.scrollTo=()=>{};
  w.structuredClone=structuredClone;
  w.AbortController=AbortController;
  w.HTMLDialogElement.prototype.showModal=function(){this.setAttribute('open','');};
  w.HTMLDialogElement.prototype.close=function(){this.removeAttribute('open');};
  const q=s=>w.document.querySelector(s);
  const click=s=>{const node=q(s);assert.ok(node,`Missing UI element: ${s}`);node.click();};
  const change=(s,value)=>{const node=q(s);node.value=value;node.dispatchEvent(new w.Event('change',{bubbles:true}));};
  async function until(predicate){const timeout=Date.now()+5000;while(!predicate()){if(Date.now()>timeout)assert.fail('UI did not reach expected state: '+q('#app').textContent.slice(-1000));await new Promise(resolve=>setTimeout(resolve,20));}}
  const submit=s=>q(s).dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
  try{
    w.eval(await fs.readFile(new URL('../public/app.js',import.meta.url),'utf8'));
    await until(()=>q('#auth-form'));
    assert.match(q('#app').textContent,/Welcome to NutriMess/);
    click('[data-action="auth-register"]');
    assert.equal(q('[name="sex"]'),null);
    assert.equal(q('[name="password"]').getAttribute('minlength'),null);
    change('[name="email"]','demo@example.com');change('[name="password"]','p');change('[name="name"]','Demo Student');
    submit('#auth-form');await until(()=>q('#profile-form'));
    click('[data-view="overview"]');await until(()=>q('h1')?.textContent==='Eat well. Feel ready.');
    assert.match(q('#main').textContent,/first meal/);
    click('[data-view="profile"]');await until(()=>q('#profile-form'));
    assert.equal(q('[name="sex"]'),null);assert.equal(w.document.querySelectorAll('[name="gender"]').length,1);
    change('[name="name"]','Demo Student');
    click('[data-action="preference-open"]');click('[data-action="food-pick"][data-food="guava"]');
    assert.ok(q('[data-preference="guava"]'));
    submit('#profile-form');await until(()=>q('#toast').textContent.includes('Profile saved'));
    click('[data-view="menu"]');await until(()=>q('#college-select'));
    const check=q('[data-attendance="0"][data-meal="breakfast"]');check.checked=false;check.dispatchEvent(new w.Event('change',{bubbles:true}));
    click('[data-action="menu-add"][data-day="0"][data-meal="breakfast"]');
    click('[data-action="food-pick"][data-food="guava"]');
    change('#college-name','Demo hostel menu');
    click('[data-action="menu-save"]');await until(()=>q('#toast').textContent.includes('Menu saved'));
    const saved=await (await w.fetch('/api/state')).json();
    assert.equal(saved.attendance[0].breakfast,false);assert.ok(saved.menu[0].breakfast.includes('guava'));assert.equal(saved.profile.name,'Demo Student');assert.ok(saved.profile.preferred.includes('guava'));
    click('[data-view="journal"]');await until(()=>q('#journal-date'));
    assert.ok([...w.document.querySelectorAll('[data-view="journal"]')].some(button=>button.textContent.trim()==='Log meals'));
    click('[data-action="log-open"]');
    assert.ok(q('#meal-log-form'));assert.match(q('#dialog').textContent,/Your menu is ready/);
    click('[data-action="meal-select-menu"]');
    click('[data-action="meal-add"][data-filter="dairy"]');
    assert.equal(q('[data-action="picker-filter"][data-filter="dairy"]').getAttribute('aria-pressed'),'true');
    click('[data-action="food-pick"][data-food="curd"]');
    const yogurtRow=[...w.document.querySelectorAll('.meal-editor-row')].find(r=>r.textContent.includes('Plain curd'));
    const yogurtInput=yogurtRow.querySelector('[data-meal-portions]');yogurtInput.value='1.5';yogurtInput.dispatchEvent(new w.Event('change',{bubbles:true}));
    submit('#meal-log-form');
    await until(()=>q('#toast').textContent.includes('Meal saved'));
    assert.match(q('#main').textContent,/Whole cow milk/);
    let mealState=await (await w.fetch('/api/state')).json();
    assert.equal(mealState.logs.find(l=>l.foodId==='curd').portions,1.5);
    assert.ok(mealState.logs.some(l=>l.foodId==='poha'||l.foodId==='idli'||l.foodId==='upma'||l.foodId==='dosa'));
    assert.ok(!mealState.menu.some(d=>d.breakfast.includes('curd')));
    click('[data-action="meal-edit"][data-meal="breakfast"]');
    const editedYogurtRow=[...w.document.querySelectorAll('.meal-editor-row')].find(r=>r.textContent.includes('Plain curd'));
    assert.equal(editedYogurtRow.querySelector('[data-meal-portions]').value,'1.5');
    editedYogurtRow.querySelector('[data-meal-portions]').value='0.5';editedYogurtRow.querySelector('[data-meal-portions]').dispatchEvent(new w.Event('change',{bubbles:true}));
    submit('#meal-log-form');await until(()=>!q('#dialog').open);
    mealState=await (await w.fetch('/api/state')).json();
    assert.equal(mealState.logs.filter(l=>l.foodId==='curd').length,1);
    assert.equal(mealState.logs.find(l=>l.foodId==='curd').portions,.5);
    assert.match(q('#main').textContent,/Nutrition over time/);
    assert.match(q('#main').textContent,/target-days/);
    click('[data-view="planner"]');await until(()=>q('#week-start'));
    click('[data-action="generate"]');await until(()=>q('#main').textContent.includes('Your weekly nutrient outlook'));
    assert.ok(q('.week-nutrient-grid'));assert.match(q('#main').textContent,/incomplete data/);
    click('[data-action="strategy-suggested"]');await until(()=>q('#strategy-form'));
    for(const day of w.document.querySelectorAll('.strategy-day'))assert.ok([...day.querySelectorAll('.strategy-meal p')].some(p=>p.textContent!=='No foods selected'));
    change('#strategy-name','My edited suggestion');
    click('[data-action="strategy-meal"][data-day="0"][data-meal="breakfast"]');
    assert.match(q('#dialog').textContent,/Edit strategy meal/);
    click('[data-action="meal-clear"]');
    click('[data-action="meal-add"]');click('[data-action="food-pick"][data-food="curd"]');
    submit('#meal-log-form');assert.ok(!q('#dialog').open);
    submit('#strategy-form');await until(()=>q('#toast').textContent.includes('Strategy saved'));
    let strategies=(await (await w.fetch('/api/state')).json()).strategies;
    assert.ok(strategies.at(-1).days.every(d=>d.entries.length>0));
    assert.equal(strategies.at(-1).name,'My edited suggestion');
    assert.deepEqual(strategies.at(-1).days[0].entries.filter(e=>e.meal==='breakfast').map(e=>e.foodId),['curd']);
    assert.ok(q('a[download][href$="/pdf"]'));
    click('[data-action="strategy-activate"]');await until(()=>q('#toast').textContent.includes('Strategy activated'));
    assert.match(q('#main').textContent,/Active: My edited suggestion/);
    click('[data-action="strategy-new"]');change('#strategy-name','My own empty plan');
    click('[data-action="strategy-meal"][data-day="6"][data-meal="breakfast"]');
    assert.equal(q('#meal-log-date').disabled,true,'Reusable strategy days must not be blocked by actual-log date validation');
    const emptyRows=[...w.document.querySelectorAll('.meal-editor-row')];
    assert.ok(emptyRows.length>=saved.menu[6].breakfast.length);
    for(const row of emptyRows){
      assert.equal(row.querySelector('[data-meal-portions]').value,'0');
      assert.equal(row.querySelector('[data-meal-portions]').disabled,false);
      assert.equal(row.querySelector('[data-meal-check]').checked,false);
    }
    const zeroInput=emptyRows[0].querySelector('[data-meal-portions]');
    zeroInput.value='0.75';zeroInput.dispatchEvent(new w.Event('change',{bubbles:true}));
    assert.equal(emptyRows[0].querySelector('[data-meal-check]').checked,true);
    click('[data-action="meal-clear"]');
    assert.equal(q('#meal-log-form').checkValidity(),true);
    submit('#meal-log-form');
    submit('#strategy-form');await until(()=>q('#toast').textContent.includes('Strategy saved'));
    strategies=(await (await w.fetch('/api/state')).json()).strategies;
    assert.equal(strategies.length,2);assert.ok(strategies.at(-1).days.every(d=>d.entries.length===0));
    click('[data-view="planner"]');await until(()=>q('#week-start'));
    click('[data-action="extra-open"]');click('[data-action="food-pick"][data-food="orange"]');submit('#food-form');
    await until(()=>q('#toast').textContent.includes('Extra added'));
    assert.match(q('#main').textContent,/Extras for this week/);
    click('[data-view="about"]');await until(()=>q('.evidence-table'));
    assert.match(q('.evidence-table').textContent,/No fixed rate applied/);
    assert.match(q('#main').textContent,/Supplemental Indian recipes/);
    click('[data-view="planner"]');await until(()=>q('#week-start'));
    click('[data-action="extra-open"]');
    q('#food-search').value='sambar';q('#food-search').dispatchEvent(new w.Event('input',{bubbles:true}));
    click('[data-action="food-pick"][data-food="indb-ASC167"]');
    assert.match(q('#dialog').textContent,/source batch/);
    assert.doesNotMatch(q('#dialog').textContent,/null g/);
    submit('#food-form');await until(()=>!q('#dialog').open);
    click('[data-view="journal"]');await until(()=>q('#journal-date'));
    click('[data-action="meal-edit"][data-meal="dinner"]');
    click('[data-action="meal-add"]');
    q('#food-search').value='sambar';q('#food-search').dispatchEvent(new w.Event('input',{bubbles:true}));
    click('[data-action="food-pick"][data-food="indb-ASC167"]');
    submit('#meal-log-form');await until(()=>!q('#dialog').open);
    const importedLogState=await (await w.fetch('/api/state')).json();
    assert.ok(importedLogState.logs.some(l=>l.foodId==='indb-ASC167'&&l.meal==='dinner'));
    click('[data-view="menu"]');await until(()=>q('#college-select'));
    assert.ok(q('#college-select option[value="nitk-uploaded"]'));
    change('#college-select','nitk-uploaded');
    assert.match(q('#main').textContent,/NITK/);
    assert.equal(q('.menu-grid .food-nutrition'),null,'Menu grid should contain no nutrient panels');
    click('[data-view="nutrition"]');await until(()=>q('h1')?.textContent==='Menu items nutrition stats');
    const nutritionRows=[...w.document.querySelectorAll('[data-nutrition-food]')];
    assert.equal(nutritionRows.length,96);
    assert.equal(new Set(nutritionRows.map(row=>row.dataset.nutritionFood)).size,96);
    assert.match(q('#main').textContent,/Nutrition per serving/);
    assert.match(q('#main').textContent,/1 idli · 60 g/);
    assert.doesNotMatch(q('#main').textContent,/Nutrition per 100 g/);
    assert.match(q('#main').textContent,/Sodium/);
    assert.match(q('#main').textContent,/modeled zero/);
    assert.match(q('#main').textContent,/Model assumptions and revisions/);
    assert.match(q('#main').textContent,/Portion evidence/);
    click('#main [data-view="menu"]');await until(()=>q('#college-select'));
    assert.equal(q('#college-select').value,'nitk-uploaded','Nutrition view should preserve menu edits');
    click('[data-action="menu-save"]');await until(()=>q('#toast').textContent.includes('Menu saved'));
    const nitkState=await (await w.fetch('/api/state')).json();
    assert.equal(nitkState.collegeId,'nitk-uploaded');assert.equal(nitkState.menu[0].breakfast.length,12);
    click('[data-view="strategies"]');await until(()=>q('[data-action="strategy-new"]'));
    click('[data-action="strategy-new"]');click('[data-action="strategy-meal"][data-day="0"][data-meal="breakfast"]');
    assert.equal(w.document.querySelectorAll('.meal-editor-row').length,12);
    assert.ok([...w.document.querySelectorAll('[data-meal-portions]')].every(input=>input.value==='0'));
    assert.equal(errors.length,0,errors.map(String).join('\n'));
  }finally{w.close();server.closeAllConnections();await new Promise(resolve=>server.close(resolve));}
});
